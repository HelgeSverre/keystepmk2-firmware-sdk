#!/usr/bin/env python3
"""Take the display fonts out of a stock firmware image for use with the SDK.

    uv run tools/fontextract.py list                       # the fonts in stock 1.0.2
    uv run tools/fontextract.py show 0 "Tempo 120.0"       # preview a text in font 0
    uv run tools/fontextract.py header -o sdk/build/generated/keystep_fonts.h

The stock firmware carries its fonts as Windows .FNT version 2 raster fonts: a 118-byte header,
a table of (width, offset) per character, then each glyph as columns of bytes, eight pixels wide
and the font's height tall, most significant bit on the left.

The fonts are Arturia's (and their designers'). The generated header is built from your own copy
of the firmware and belongs in a build folder, not in a repository.
"""

from __future__ import annotations

import argparse
import struct
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fwpack

ROOT = Path(__file__).resolve().parent.parent
STOCK = ROOT / "firmware/keystep_mk2__1_0_2.ks2fw"
NAMES = ("small", "large", "font2", "font3")


@dataclass
class Font:
    address: int  # in the processor's memory
    height: int
    ascent: int
    first: int
    last: int
    copyright: str
    glyphs: list[tuple[int, bytes]]  # per character: width, column bytes

    def rows(self, char: int) -> list[str]:
        width, data = self.glyphs[char - self.first] if self.first <= char <= self.last else self.glyphs[0]
        out = []
        for y in range(self.height):
            bits = "".join(f"{data[c * self.height + y]:08b}" for c in range((width + 7) // 8))
            out.append(bits[:width])
        return out

    def render(self, text: str) -> str:
        chars = [self.rows(c) for c in text.encode("latin-1", "replace")]
        return "\n".join(
            "".join(rows[y] for rows in chars).replace("0", " ").replace("1", "█") for y in range(self.height)
        )


def parse(body: bytes, at: int) -> Font | None:
    """A .FNT version 2 font starting at `at`, or None if the bytes there are not one."""
    if at + 118 > len(body):
        return None
    version, size = struct.unpack_from("<HI", body, at)
    if version != 0x0200 or not 118 < size <= 0x8000 or at + size > len(body):
        return None
    font_type, _points, _vres, _hres, ascent = struct.unpack_from("<5H", body, at + 66)
    height = struct.unpack_from("<H", body, at + 88)[0]
    first, last = body[at + 95], body[at + 96]
    if font_type & 1 or not 4 <= height <= 64 or last < first:
        return None
    glyphs = []
    for i in range(last - first + 1):
        width, offset = struct.unpack_from("<HH", body, at + 118 + 4 * i)
        length = (width + 7) // 8 * height
        if width > 64 or offset + length > size:
            return None
        glyphs.append((width, body[at + offset : at + offset + length]))
    text = body[at + 6 : at + 66].split(b"\0")[0].decode("latin-1").strip()
    return Font(fwpack.LOAD_ADDRESS + at, height, ascent, first, last, text, glyphs)


def find(image_path: Path) -> list[Font]:
    image, _ = fwpack.read_image(image_path)
    body = image[fwpack.HEADER_SIZE :]
    fonts, at = [], 0
    while (at := body.find(b"\x00\x02", at)) >= 0:
        font = parse(body, at) if at % 4 == 0 else None
        fonts += [font] if font else []
        at += 2
    return fonts


def header(fonts: list[Font], source: str) -> str:
    out = [
        f"/* Generated by tools/fontextract.py from {source}. The fonts belong to their owners:",
        " * keep this file out of repositories. */",
        "#ifndef KEYSTEP_FONTS_H",
        "#define KEYSTEP_FONTS_H",
        '#include "keystep.h"',
        "",
    ]
    for name, font in zip(NAMES, fonts, strict=False):
        bits, offsets, widths = bytearray(), [], []
        for width, data in font.glyphs:
            offsets.append(len(bits))
            widths.append(width)
            bits += data

        def table(values, per_line):
            lines = [", ".join(str(v) for v in values[i : i + per_line]) for i in range(0, len(values), per_line)]
            return "    " + ",\n    ".join(lines) + ",\n"

        out += [
            f"/* {font.height} pixels tall, characters {font.first:#x} to {font.last:#x}"
            + (f"; {font.copyright}" if font.copyright else "")
            + " */",
            f"static const uint8_t ks_font_{name}_bits[] = {{\n{table(list(bits), 24)}}};",
            f"static const uint16_t ks_font_{name}_offsets[] = {{\n{table(offsets, 16)}}};",
            f"static const uint8_t ks_font_{name}_widths[] = {{\n{table(widths, 32)}}};",
            (
                f"static const ks_font ks_font_{name} = {{ {font.height}, {font.ascent}, {font.first}, {font.last}, "
                f"ks_font_{name}_offsets, ks_font_{name}_widths, ks_font_{name}_bits }};"
            ),
            "",
        ]
    out += ["#endif", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--image", type=Path, default=STOCK, help="a stock image or package (default: 1.0.2)")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("list", help="the fonts found")
    show = sub.add_parser("show", help="print a text in one of the fonts")
    show.add_argument("font", type=int)
    show.add_argument("text")
    head = sub.add_parser("header", help="write the C header for the SDK")
    head.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args()

    if not args.image.exists():
        sys.exit(f"error: {args.image} not found; fetch the stock firmware first (just fetch)")
    fonts = find(args.image)
    if not fonts:
        sys.exit("error: no fonts found in this image")
    if args.command == "list":
        for i, font in enumerate(fonts):
            widths = [w for w, _ in font.glyphs]
            print(
                f"{i}: ks_font_{NAMES[i]} at {font.address:#010x}, {font.height} px tall, ascent {font.ascent}, "
                f"characters {font.first:#x}-{font.last:#x}, widths {min(widths)}-{max(widths)}, {font.copyright!r}"
            )
    elif args.command == "show":
        print(fonts[args.font].render(args.text))
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(header(fonts, args.image.name))
        print(f"wrote {args.output} ({len(fonts)} fonts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
